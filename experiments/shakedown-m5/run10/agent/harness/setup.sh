#!/usr/bin/env bash
set -euo pipefail
mkdir -p out data
exec > >(tee out/setup.log) 2>&1
# Select only layouts discovered in the supplied probe.
if [[ -x /usr/local/cuda/bin/nvcc && -f /usr/local/cuda/include/cuda_runtime.h && -f /usr/local/cuda/lib64/libcudart.so ]]; then
  compiler=/usr/local/cuda/bin/nvcc; inc=/usr/local/cuda/include; lib=/usr/local/cuda/lib64; root=/usr/local/cuda
elif [[ -x /usr/lib/cuda/bin/nvcc && -f /usr/lib/cuda/include/cuda_runtime.h && -f /usr/lib/cuda/lib64/libcudart.so ]]; then
  compiler=/usr/lib/cuda/bin/nvcc; inc=/usr/lib/cuda/include; lib=/usr/lib/cuda/lib64; root=/usr/lib/cuda
elif [[ -x /usr/bin/nvcc && -f /usr/include/cuda_runtime.h && -f /usr/lib/x86_64-linux-gnu/libcudart.so ]]; then
  compiler=/usr/bin/nvcc; inc=/usr/include; lib=/usr/lib/x86_64-linux-gnu; root=''
else
  echo 'No complete probed CUDA development layout' >&2; exit 1
fi
ls -l "$compiler" "$inc/cuda_runtime.h" "$lib/libcudart.so"
# Restrict any dependency installation to the sole enabled source in the probe.
apt_options=(-o Dir::Etc::sourcelist=/etc/apt/sources.list.d/nvidia-docker-container.list -o Dir::Etc::sourceparts=-)
for package in cmake g++ git python3 patch; do
  if ! command -v "$package" >/dev/null; then
    if ! sudo apt-get "${apt_options[@]}" update || ! sudo apt-get "${apt_options[@]}" install -y "$package"; then
      if [[ $package == cmake ]]; then
        python3 -m pip install --user cmake==3.31.6
      else
        echo "Required tool unavailable from probed apt source: $package" >&2; exit 1
      fi
    fi
  fi
done
cmake_bin=$(command -v cmake)
"$cmake_bin" --version
pin=db3eea23946bca2e90a75eca2b5b3e07158a9e11
if [[ ! -d baseline-published/.git ]]; then
  git clone --branch v12.8 --depth 1 https://github.com/NVIDIA/cuda-samples.git baseline-published
fi
[[ $(git -C baseline-published rev-parse HEAD) == "$pin" ]] || { echo 'Baseline pin mismatch'; exit 1; }
git -C baseline-published checkout --detach "$pin"
base=$(realpath baseline-published)
printf 'export CUDA_COMPILER=%q\nexport CUDA_INCLUDE=%q\nexport CUDA_LIB=%q\nexport CUDA_ROOT=%q\nexport PATH=%q:"$PATH"\nexport LD_LIBRARY_PATH=%q:"${LD_LIBRARY_PATH:-}"\n' "$compiler" "$inc" "$lib" "$root" "$(dirname "$compiler")" "$lib" > "$base/cuda-env.sh"
printf 'export CMAKE_BIN=%q\n' "$cmake_bin" >> "$base/cuda-env.sh"
source "$base/cuda-env.sh"
flags=(-DCMAKE_BUILD_TYPE=Release "-DCMAKE_CUDA_COMPILER=$compiler" "-DCUDAToolkit_INCLUDE_DIR=$inc" "-DCUDA_cudart_LIBRARY=$lib/libcudart.so" "-DCMAKE_CUDA_FLAGS=-I$inc -L$lib")
[[ -z $root ]] || flags+=("-DCUDAToolkit_ROOT=$root")
sample=Samples/5_Domain_Specific/MonteCarloMultiGPU
"$cmake_bin" -S "$base/$sample" -B "$base/build-anchor" "${flags[@]}"
"$cmake_bin" --build "$base/build-anchor" --target MonteCarloMultiGPU --parallel 16
if [[ ! -d $base/representative-source ]]; then
  rm -rf "$base/representative-source.tmp"
  mkdir "$base/representative-source.tmp"
  git -C "$base" archive "$pin" | tar -x -C "$base/representative-source.tmp"
  (cd "$base/representative-source.tmp"; patch -l -p1 <<'PATCH'
--- a/Samples/5_Domain_Specific/MonteCarloMultiGPU/MonteCarloMultiGPU.cpp
+++ b/Samples/5_Domain_Specific/MonteCarloMultiGPU/MonteCarloMultiGPU.cpp
@@ -1 +1 @@
-    int nOptions = 8 * 1024;
+    int nOptions = 1024 * 1024;
PATCH
  )
  mv "$base/representative-source.tmp" "$base/representative-source"
fi
"$cmake_bin" -S "$base/representative-source/$sample" -B "$base/build-mc" "${flags[@]}"
"$cmake_bin" --build "$base/build-mc" --target MonteCarloMultiGPU --parallel 16
mkdir -p "$base/anchor-run"
ln -sfn ../build-anchor "$base/anchor-run/build-mc"
test -x "$base/build-mc/MonteCarloMultiGPU"
test -x "$base/build-anchor/MonteCarloMultiGPU"
printf '%s\n' 'Generated by published srand(123) and cuRAND; no external downloads.' > data/README.txt
