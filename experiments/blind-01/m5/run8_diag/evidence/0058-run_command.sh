import argparse
import json
import math
import os
import shutil
import struct
import subprocess
import time
from pathlib import Path

import biotite.structure.io as strucio

p = argparse.ArgumentParser()
p.add_argument('--cases', required=True)
p.add_argument('--out', required=True)
p.add_argument('--mpi-np', type=int, required=True)
p.add_argument('--n-solutions', type=int, required=True)
p.add_argument('--gpu-count', type=int, required=True)
a = p.parse_args()
if (a.mpi_np, a.n_solutions, a.gpu_count) != (8, 100, 0):
    raise ValueError('Published configuration mismatch')
if os.environ['CUDA_VISIBLE_DEVICES'] != '' or os.environ['OMP_NUM_THREADS'] != '1':
    raise ValueError('Published environment mismatch')
cases = json.loads(Path(a.cases).read_text())
if len(cases) != 93 or len({c['id'] for c in cases}) != 93:
    raise ValueError('Missing fixed cases')
cases = sorted(cases, key=lambda c: c['id'])
out = Path(a.out)
out.mkdir(parents=True, exist_ok=True)
run = out / ('run-' + str(time.time_ns()))
run.mkdir()
print('CONFIG ' + json.dumps({
    'mpi_np': a.mpi_np, 'n_solutions': a.n_solutions,
    'gpu_count': a.gpu_count, 'CUDA_VISIBLE_DEVICES': os.environ['CUDA_VISIBLE_DEVICES'],
    'cases': len(cases), 'cwd': os.getcwd(), 'OMP_NUM_THREADS': os.environ['OMP_NUM_THREADS'],
}), flush=True)
bindir = Path('baseline-published/frodock3_linux64/bin')
mpi = ['/usr/bin/mpirun', '-np', str(a.mpi_np), '--use-hwthread-cpus']


def valid_mrc(path):
    # Validate actual output, including complete voxel data, rather than status 1
    # returned by the legacy MPI grid executable after writing its map.
    with path.open('rb') as f:
        header = f.read(1024)
    if len(header) != 1024:
        raise ValueError('Truncated MRC header: ' + str(path))
    for endian in ('<', '>'):
        nx, ny, nz, mode = struct.unpack_from(endian + '4i', header)
        nsymbt = struct.unpack_from(endian + 'i', header, 92)[0]
        width = {0: 1, 1: 2, 2: 4, 6: 2}.get(mode)
        if width and min(nx, ny, nz) > 0 and nsymbt >= 0:
            if path.stat().st_size == 1024 + nsymbt + nx * ny * nz * width:
                return
    raise ValueError('Invalid or incomplete MRC output: ' + str(path))


def stage(command, work, outputs=(), maps=False, label='stage'):
    print('COMMAND ' + json.dumps(command), flush=True)
    # The published adapter does not check return codes. Keep that behavior,
    # but require fresh stage products. Every case uses a new scratch directory.
    log = work / (label + '.log')
    with log.open('wb') as stream:
        result = subprocess.run(command, cwd=work, stdout=stream, stderr=subprocess.STDOUT)
    with log.open(errors='replace') as stream:
        for line in stream:
            print(line, end='', flush=True)
    print('STAGE_STATUS ' + json.dumps({'stage': label, 'returncode': result.returncode}), flush=True)
    for name in outputs:
        path = work / name
        if not path.is_file() or path.stat().st_size == 0:
            raise ValueError('Missing stage output: ' + str(path))
        if maps:
            valid_mrc(path)
    if not outputs and log.stat().st_size == 0:
        raise ValueError('Missing stage output: ' + str(log))


total_wall = 0.0
for case in cases:
    cid = case['id']
    if Path(cid).name != cid or cid in ('.', '..'):
        raise ValueError('Invalid case ID')
    work = run / 'scratch' / cid
    work.mkdir(parents=True)
    dst = run / 'results/frodock' / cid / 'apo_decoys'
    dst.mkdir(parents=True)
    start = time.perf_counter()
    # Inputs generated by setup can contain its original working directory.
    # Resolve their shared-tree suffix against this invocation's work directory.
    for role in ('receptor', 'ligand'):
        source = Path(case[role])
        if source.is_absolute():
            parts = source.parts
            try:
                source = Path(*parts[parts.index('data'):])
            except ValueError:
                raise ValueError('Input outside shared data tree')
        shutil.copyfile(source, work / (role + '.pdb'))
    pre = Path(os.path.relpath(bindir, work))
    grid = mpi + [str(pre / 'frodockgrid_mpi_gcc')]
    stage(grid + ['receptor.pdb', '-o', 'receptor_W.mrc'], work,
          ['receptor_W.mrc'], True, 'grid-W')
    stage(grid + ['receptor.pdb', '-o', 'receptor_E.mrc', '-m', '1', '-t', 'A'], work,
          ['receptor_E.mrc'], True, 'grid-E')
    stage(grid + ['receptor.pdb', '-o', 'receptor_DS.mrc', '-m', '3'], work,
          ['receptor_DS.mrc'], True, 'grid-receptor-DS')
    stage(grid + ['ligand.pdb', '-o', 'ligand_DS.mrc', '-m', '3'], work,
          ['ligand_DS.mrc'], True, 'grid-ligand-DS')
    for name in ('receptor_ASA.pdb', 'ligand_ASA.pdb'):
        strucio.load_structure(str(work / name))
    stage(mpi + [str(pre / 'frodock_mpi_gcc'), 'receptor_ASA.pdb', 'ligand_ASA.pdb',
                 '-w', 'receptor_W.mrc', '-e', 'receptor_E.mrc', '--th', '10',
                 '-d', 'receptor_DS.mrc,ligand_DS.mrc', '-t', 'A', '-o', 'dock.dat',
                 '-s', str(pre / 'soap.bin')], work, ['dock.dat'], label='dock')
    stage([str(pre / 'frodockcluster_gcc'), 'dock.dat', 'ligand.pdb', '--nc',
           str(a.n_solutions), '-o', 'clust_dock.dat'], work, ['clust_dock.dat'], label='cluster')
    stage([str(pre / 'frodockview_gcc'), 'clust_dock.dat', '-r', f'1-{a.n_solutions}'],
          work, label='view')
    stage([str(pre / 'frodockview_gcc'), 'clust_dock.dat', '-r', f'1-{a.n_solutions}',
           '-p', 'ligand.pdb'], work,
          [f'ligand_{i}.pdb' for i in range(1, a.n_solutions + 1)], label='poses')
    receptor = strucio.load_structure(str(work / 'receptor.pdb'))
    for i in range(1, a.n_solutions + 1):
        ligand = strucio.load_structure(str(work / f'ligand_{i}.pdb'))
        if len(receptor) == 0 or len(ligand) == 0:
            raise ValueError('Empty pose structure')
        strucio.save_structure(str(dst / f'model_{i}.pdb'), receptor + ligand)
    elapsed = time.perf_counter() - start
    total_wall += elapsed
    print('CASE_WALL ' + json.dumps({'id': cid, 'wall_s': elapsed}), flush=True)

from pinder.eval.dockq.method import MethodMetrics
mm = MethodMetrics(run / 'results', parallel=True, allow_missing_systems=True, max_workers=8)
metrics = mm.metrics
metrics.to_csv(run / 'frodock_metrics.csv', index=False)
mm.get_leaderboard_entry().to_csv(run / 'frodock_leaderboard.csv', index=False)
selected = metrics[metrics.id.isin([c['id'] for c in cases]) &
                   (metrics.monomer_name == 'apo')].drop_duplicates(['id', 'rank'])
if len(selected) != len(cases) * a.n_solutions:
    raise ValueError('Missing measured poses')
if not all(math.isfinite(float(v)) for col in ('DockQ', 'iRMS', 'LRMS', 'Fnat') for v in selected[col]):
    raise ValueError('Invalid measured metric')
top = selected[selected['rank'] == 1].sort_values('id')
best = selected.groupby('id').DockQ.max()
counts = json.loads(Path('data/counts.json').read_text())
summary = {
    'wall_s': total_wall, 'gpu_count': 0, 'case_count': len(cases), 'pose_count': len(selected),
    'DockQ': float(top.DockQ.mean()), 'top1_DockQ': float(top.DockQ.mean()),
    'best100_DockQ': float(best.mean()), 'iRMSD': float(top.iRMS.mean()),
    'LRMSD': float(top.LRMS.mean()), 'fnat': float(top.Fnat.mean()),
    'acceptable_fraction': float((best >= 0.23).sum() / len(cases)),
    'poses_per_s': len(selected) / total_wall,
    'anchors': dict(counts, **{'dockq-acceptable': float(top.iloc[0].DockQ)}),
    'run_dir': str(run),
}
print('MEASUREMENT ' + json.dumps(summary, allow_nan=False), flush=True)
